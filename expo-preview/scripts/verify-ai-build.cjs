const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const sha256 = value => createHash('sha256').update(value).digest('hex');
const requiredInputs = ['ai-lab/build.mjs', 'ai-lab/engine-entry.mjs', 'ai-lab/package.json', 'ai-lab/package-lock.json', 'src/ai/contracts.ts', 'src/ai/LICENSE.wllama', 'src/ai/LICENSE.llama.cpp'];

function verifyAIBuild(root) {
  root = path.resolve(root);
  const manifestBytes = fs.readFileSync(path.join(root, 'src/ai/engine-manifest.json'));
  const manifest = JSON.parse(manifestBytes.toString('utf8'));
  const inputs = manifest.buildInputsSHA256;
  if (!inputs || typeof inputs !== 'object' || Array.isArray(inputs) || requiredInputs.some(name => !Object.hasOwn(inputs, name))) throw new Error('AI build input manifest is incomplete. Run npm run build --prefix ai-lab.');
  if (Object.keys(inputs).length > 128) throw new Error('AI build input manifest exceeds its bound.');
  for (const [relative, expected] of Object.entries(inputs)) {
    if (path.isAbsolute(relative) || relative.split(/[\\/]/).some(part => part === '..' || part === '' || part === '.')) throw new Error('Unsafe AI build input path.');
    if (typeof expected !== 'string' || !/^[a-f0-9]{64}$/.test(expected)) throw new Error(`Invalid AI build input hash: ${relative}`);
    if (sha256(fs.readFileSync(path.join(root, relative))) !== expected) throw new Error(`Stale AI build input: ${relative}. Run npm run build --prefix ai-lab.`);
  }
  const generated = fs.readFileSync(path.join(root, 'src/ai/engine.generated.ts'));
  if (generated.length !== manifest.generatedModuleBytes || sha256(generated) !== manifest.generatedModuleSHA256) throw new Error('Generated AI module hash/size differs from its build manifest.');
  const moduleText = generated.toString('utf8');
  const declaration = 'export const LOCAL_AI_HTML = ';
  const body = moduleText.slice(moduleText.indexOf('\n') + 1);
  if (!moduleText.startsWith('// Generated by ai-lab/build.mjs.') || !body.startsWith(declaration) || !body.endsWith(';\n')) throw new Error('Unexpected generated AI module format.');
  // Parse the JSON string literal; never eval or import the generated module.
  const html = JSON.parse(body.slice(declaration.length, -2));
  if (typeof html !== 'string' || Buffer.byteLength(html) !== manifest.nativeHTMLBytes || sha256(html) !== manifest.nativeHTMLSHA256) throw new Error('Embedded AI HTML hash/size differs from its build manifest.');
  return { buildInputs: Object.keys(inputs).length, generatedModuleBytes: generated.length, generatedModuleSHA256: sha256(generated), nativeHTMLBytes: Buffer.byteLength(html), nativeHTMLSHA256: sha256(html), manifestSHA256: sha256(manifestBytes) };
}

module.exports = {verifyAIBuild};
if (require.main === module) {
  try { console.log(JSON.stringify(verifyAIBuild(path.resolve(__dirname, '..')), null, 2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
