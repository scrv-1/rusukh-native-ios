const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {verifyAIBuild} = require('../scripts/verify-ai-build.cjs');
const hash = value => createHash('sha256').update(value).digest('hex');
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'rusukh-ai-build-'));
  t.after(() => fs.rmSync(root, {recursive:true, force:true}));
  const write = (relative, value) => { const file = path.join(root,relative);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,value); };
  const inputs = ['ai-lab/build.mjs','ai-lab/engine-entry.mjs','ai-lab/package.json','ai-lab/package-lock.json','src/ai/contracts.ts','src/ai/LICENSE.wllama','src/ai/LICENSE.llama.cpp'];
  const buildInputsSHA256 = {};
  for(const input of inputs) {write(input,input);buildInputsSHA256[input]=hash(input);}
  const html='<html>fixture, no inference</html>';
  const generated='// Generated by ai-lab/build.mjs. fixture\nexport const LOCAL_AI_HTML = '+JSON.stringify(html)+';\n';
  const manifest={buildInputsSHA256,generatedModuleBytes:Buffer.byteLength(generated),generatedModuleSHA256:hash(generated),nativeHTMLBytes:Buffer.byteLength(html),nativeHTMLSHA256:hash(html)};
  write('src/ai/engine.generated.ts',generated);
  const saveManifest=()=>write('src/ai/engine-manifest.json',JSON.stringify(manifest));saveManifest();
  return {root,write,manifest,saveManifest,generated,inputs};
}
test('release verifies the real rebuilt module, embedded HTML and current first-party inputs',()=>{
 const result=verifyAIBuild(path.resolve(__dirname,'..'));assert.ok(result.buildInputs>=7);assert.ok(result.generatedModuleBytes>result.nativeHTMLBytes);assert.match(result.manifestSHA256,/^[a-f0-9]{64}$/);
});
test('changing any required source/config/license after build fails before release tests',t=>{
 const f=fixture(t);assert.equal(verifyAIBuild(f.root).buildInputs,7);
 for(const input of f.inputs){f.write(input,input+' changed');assert.throws(()=>verifyAIBuild(f.root),/Stale AI build input/);f.write(input,input);}
});
test('altering generated bytes fails even if the stored HTML hash is unchanged',t=>{
 const f=fixture(t);f.write('src/ai/engine.generated.ts',f.generated+'\n');assert.throws(()=>verifyAIBuild(f.root),/Generated AI module/);
});
test('a consistent module checksum cannot conceal a mismatched embedded HTML checksum',t=>{
 const f=fixture(t);f.manifest.nativeHTMLSHA256='0'.repeat(64);f.saveManifest();assert.throws(()=>verifyAIBuild(f.root),/Embedded AI HTML/);
});
test('removing the contract input or adding a traversal path is rejected',t=>{
 const f=fixture(t);delete f.manifest.buildInputsSHA256['src/ai/contracts.ts'];f.saveManifest();assert.throws(()=>verifyAIBuild(f.root),/incomplete/);
 f.manifest.buildInputsSHA256['src/ai/contracts.ts']=hash('src/ai/contracts.ts');f.manifest.buildInputsSHA256['../escape']=hash('anything');f.saveManifest();assert.throws(()=>verifyAIBuild(f.root),/Unsafe AI build input path/);
});
