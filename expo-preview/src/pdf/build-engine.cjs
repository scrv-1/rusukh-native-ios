/* Dev-only build. Install pdfjs-dist@6.5.438 and esbuild@0.25.12 in an isolated tooling prefix. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const tooling = process.env.RUSUKH_PDF_TOOLING;
if (!tooling) throw new Error('Set RUSUKH_PDF_TOOLING to an isolated npm prefix.');
const packagePath = path.join(tooling, 'node_modules/pdfjs-dist');
const meta = JSON.parse(fs.readFileSync(path.join(packagePath, 'package.json'), 'utf8'));
if (meta.version !== '6.5.438' || meta.license !== 'Apache-2.0') throw new Error('Unexpected PDF.js version/license');
const esbuild = require(path.join(tooling, 'node_modules/esbuild'));
const result = esbuild.buildSync({ entryPoints: [path.join(__dirname, 'engine-entry.js')], bundle: true,
  write: false, minify: true, platform: 'browser', format: 'iife', target: 'safari16.4',
  nodePaths: [path.join(tooling, 'node_modules')], legalComments: 'inline' });
const source = result.outputFiles[0].text;
const hash = crypto.createHash('sha256').update(source).digest('hex');
fs.writeFileSync(path.join(__dirname, 'engine.generated.ts'),
  '// Generated by build-engine.cjs; PDF.js 6.5.438 Apache-2.0. See LICENSE.pdfjs.\n' +
  'export const PDF_ENGINE_SHA256 = ' + JSON.stringify(hash) + ';\n' +
  'export const PDF_ENGINE_SOURCE = ' + JSON.stringify(source) + ';\n');
fs.copyFileSync(path.join(packagePath, 'LICENSE'), path.join(__dirname, 'LICENSE.pdfjs'));
fs.writeFileSync(path.join(__dirname, 'engine-manifest.json'), JSON.stringify({
  package: 'pdfjs-dist', version: meta.version, license: meta.license, source: 'https://github.com/mozilla/pdf.js',
  registry: 'https://registry.npmjs.org/pdfjs-dist/-/pdfjs-dist-6.5.438.tgz',
  npmIntegrity: 'sha512-vg8Pw1x+AFKy4AMDvhuWl5cOYV8d698UoEANoFFhc79hqXDnZQqnOXoxw3HG907WHOg1JYOvLhP756boddFxpA==',
  engineSha256: hash, engineBytes: Buffer.byteLength(source), bundler: 'esbuild@0.25.12',
  externalAssets: false, wasm: false, networkInputs: false
}, null, 2) + '\n');
console.log(JSON.stringify({ version: meta.version, bytes: Buffer.byteLength(source), sha256: hash }));
